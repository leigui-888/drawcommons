# -*- coding: utf-8 -*-
"""W7 五项承诺的锁层级：承诺的强度取决于它被锁在哪一层

为什么要有这个脚本：
    "永不收费""不商用数据""不圈地""资产不分配""可退出"——这五句写在 09 的 §0.1。
    读起来像五道铁锁，实际强度差得很远：
        锁在许可层 → 不可撤销（许可一旦授出，不能收回）
        锁在章程层 → 75% + 人类否决（改起来要动员大多数人）
        锁在协议层 → 取决于协议自身的修订条款（通常平台单方 + 提前通知）
    三项承诺锁在哪一层，决定了它是"永远"还是"直到下一次改版"。

    本脚本不做文本匹配，只把 W5-04 章程 14 条、09 §0.1/§3.10/§1.17、W6-01 许可矩阵
    三处已经写下的东西摊成一张 5×3 表，然后回答一个问题：
    **这五项承诺里，有几项能在一次协议改版中消失？**

用法：python promise_lock.py
"""

# 锁的三层：名称、修订门槛、当前是否生效
LAYERS = [
    ("协议 0.1", "平台单方修订 + 提前通知（典型条款）", False,
     "协议附条件生效（计划生效日 2026-12-21，条件未满足则顺延），截至该日不生效"),
    ("章程 14 条", "成员大会 75% + 人类成员否决", False,
     "章程未签署（无主体），当前不生效"),
    ("许可 / 商标", "不可撤销（授出即不可收回）", True,
     "已随仓库落地（W6-L2，git 53f6cad），当前生效"),
]

# 每项承诺在每层的落点："" = 未锁定，"△" = 间接/可被解释，具体条文号 = 直接锁定
PROMISES = [
    ("P1 永不收费",
     {"协议 0.1": "0.1.2 / 1.3.6", "章程 14 条": "△ #1 非交易性供养 / #3 业务范围", "许可 / 商标": ""},
     "收费一旦发生即不可逆（退款也留痕）"),
    ("P2 不商用数据",
     {"协议 0.1": "3.10（隐私政策）", "章程 14 条": "", "许可 / 商标": "⚠ CC-BY-4.0 允许下游商用"},
     "数据卖过一次即永久失去公信力"),
    ("P3 不圈地",
     {"协议 0.1": "0.1.1 / 3.10.3", "章程 14 条": "#9 反俘获", "许可 / 商标": "⚠ CC0 不限制任何用法"},
     "圈地是渐进过程，没有单一时点"),
    ("P4 资产不分配",
     {"协议 0.1": "0.1.5 / 1.2.5", "章程 14 条": "#2 / #8 / #11", "许可 / 商标": ""},
     "分配一次即构成事实上的营利"),
    ("P5 可退出与迁移",
     {"协议 0.1": "1.17", "章程 14 条": "", "许可 / 商标": ""},
     "退出能力是公共品的底线，也是最容易在改版中被删的一条"),
]


def sec(t):
    print()
    print(t)
    print("-" * len(t))


def part1():
    sec("§1 5 × 3 锁层级矩阵")
    head = f"{'承诺':16}" + "".join(f"{n:26}" for n, _, _, _ in LAYERS)
    print(head)
    for name, row, why in PROMISES:
        line = f"{name:16}"
        for ln, _, _, _ in LAYERS:
            v = row[ln]
            cell = v if v else "—"
            line += f"{cell[:22]:26}"
        print(line)
    print()
    print("  直接锁定（有条文号） / △ 间接（可被解释） / ⚠ 反向（许可明确允许） / — 未提及")


def part2():
    sec("§2 计数：三层各自锁住了几项")
    total = len(PROMISES)
    for ln, threshold, active, note in LAYERS:
        direct = sum(1 for _, r, _w in PROMISES if r[ln] and not r[ln].startswith(("△", "⚠")))
        indirect = sum(1 for _, r, _w in PROMISES if r[ln].startswith("△"))
        reverse = sum(1 for _, r, _w in PROMISES if r[ln].startswith("⚠"))
        empty = total - direct - indirect - reverse
        print(f"  {ln:12} 直接 {direct}/{total}  间接 {indirect}  反向 {reverse}  未提 {empty}"
              f"   {'【当前生效】' if active else '【当前不生效】'}")
        print(f"  {'':12} 门槛：{threshold}")
    print()
    print("  三个计数连起来读：")
    _c = sum(1 for _, r, _w in PROMISES if r["章程 14 条"] and not r["章程 14 条"].startswith(("△", "⚠")))
    print(f"  章程锁住 {_c} 项（不圈地、资产不分配）——这两项恰恰是最需要锁的，选对了。")
    print("  协议锁住 5 项——但协议是三件套里最容易改的一份。")
    print("  许可 0 项，且对 2 项是**反向**的：CC-BY 允许下游商用，CC0 不限制任何用法。")


def part3():
    sec("§3 许可与承诺的冲突：同一份数据，两句话方向相反")
    print("  许可（LICENSE-CC-BY-4.0.md）：任何人可以商用、改作、再分发，只需署名。")
    print("  政策（3.10.1）：平台不向任何第三方出售、出租、交换数据。")
    print()
    print("  两句不矛盾，但它们的**主语不同**，而文本里没有把这层区别写出来：")
    print("    许可的主语 = 下游使用者（你可以拿去商用）")
    print("    政策的主语 = 平台自身（我们不会卖）")
    print()
    print("  后果是可预见的：")
    print("    · 读到许可的人认为「这个项目的数据可以商用」——正确")
    print("    · 读到政策的人认为「这个项目禁止数据商用」——也正确")
    print("    · 外部评议同时读两处，会得出「自相矛盾」的结论，并要求解释")
    print()
    print("  处置不是改许可（改了就没人用），也不是改政策（改了就丢承诺），")
    print("  而是在 3.10 加一句限定主语：")
    print("    「本条约束平台自身行为，不限制任何人依 CC-BY-4.0 取得数据后的合法使用；")
    print("      平台不因该许可获得任何对价。」")
    print("  这一句把「我们不卖」与「你可以用」分开，两句话才同时成立。")


def part4():
    sec("§4 能绕过 0.1.6 的那条路")
    print("  0.1.6 写：「任何使上述性质发生改变的规则变更，即使经全体成员同意，亦属无效。」")
    print()
    print("  这句锁的是**表决程序**：不许用多数决改掉性质。")
    print("  它锁不住的是**协议修订权**——因为修订不是「变更规则」，是「发布新版本」。")
    print()
    print("  一条典型的用户协议修订条款长这样：")
    print("    「平台有权根据业务需要修订本协议，修订后提前 30 日公示，公示期满生效。」")
    print("  按这条，把 0.1.2 从「永不收费」改成「基础功能免费」，")
    print("  走的是修订程序，不是「规则变更」——0.1.6 一个字都用不上。")
    print()
    print("  这不是文字游戏，是格式条款的常规结构：")
    print("  **不可变更条款的效力，永远等于它所在文件自身的修订门槛。**")
    print("  文件可以被单方改版，里面写「永不」也没有用。")
    print()
    print("  补法（一句话，加在 0.1.6 后）：")
    print("    「本条及 §0.1 全部条款，不适用平台的单方修订程序；")
    print("      其修订须经成员大会 75% 通过、且人类成员未行使否决权，并提前 30 日公示。」")
    print()
    print("  加这一句的代价：项目在只有 1 个成员时，改 0.1 需要 75% 的 1 人 = 1 人。")
    print("  这个代价是假的——1 人阶段本来就没有「单方 vs 多方」的区别。")
    print("  而它换来的是：等真有 100 个成员时，那句话已经在那儿了。")


def main():
    part1()
    part2()
    part3()
    part4()

    sec("§5 汇总")
    total = len(PROMISES)
    direct_p = sum(1 for _, r, _w in PROMISES if r["协议 0.1"] and not r["协议 0.1"].startswith("⚠"))
    direct_c = sum(1 for _, r, _w in PROMISES if r["章程 14 条"] and not r["章程 14 条"].startswith("△"))
    only_protocol = [n for n, r, _w in PROMISES if not r["章程 14 条"] or r["章程 14 条"].startswith("△")]
    active_direct = sum(1 for _, r, _w in PROMISES if r["许可 / 商标"] and not r["许可 / 商标"].startswith("⚠"))
    print(f"  纸面锁定：协议 {direct_p}/{total}、章程 {direct_c}/{total}、许可 {active_direct}/{total}")
    print(f"  当前生效的锁：只有许可层（章程无主体；协议附条件生效，计划生效日 2026-12-21，条件未满足则顺延）→ 而它对五项承诺覆盖 {active_direct}/{total}")
    print(f"  章程未锁、只靠协议层的：{len(only_protocol)} 项 → {'、'.join(n.split()[0] for n in only_protocol)}")
    print()
    print("  一句话：**现在唯一已经生效的约束是许可，而许可管的是别人能怎么用，不是我们不会变成什么。**")


if __name__ == "__main__":
    main()
