"""W4-04 缺口测算复算：年成本 / 两档储备 / 五类来源 / 六格缺口。"""
COST = {"人力":45000,"服务器+备份":2000,"域名+证书":300,"法务":6000,"审计":3000,"外部评议":3000,"杂项":2000}
TOTAL = sum(COST.values())
FUND = {"悲观":{"S1":8000,"S2":2000,"S3":0,"S4":0,"S5":5000},
        "中性":{"S1":12000,"S2":12000,"S3":15000,"S4":0,"S5":6000},
        "乐观":{"S1":15000,"S2":25000,"S3":30000,"S4":12000,"S5":8000}}
print(f"年成本 {TOTAL} 元；人力占比 {COST['人力']/TOTAL*100:.1f}%")
for m in (3,6):
    r = TOTAL*m/12; need = TOTAL+r
    print(f"--- 储备 {m} 个月：{r:.0f} 元，首年需求 {need:.0f} 元")
    for k,v in FUND.items():
        s=sum(v.values()); print(f"    {k}: 可用 {s} / 缺口 {need-s:.0f} / 覆盖 {s/need*100:.1f}%")
print(f"极限形态（去人力）{TOTAL-COST['人力']} 元；悲观档缺口 {TOTAL-COST['人力']-15000} 元")
